"""Generate the pinned console preset catalog without network access."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
media = json.loads((root / 'model-tools/presets.json').read_text())
voices = json.loads((root / 'model-tools/voices.json').read_text())
kokoro_voices = voices['kokoro']
kokoro_revision = 'c64650d0950e0b718b6eeb2f18620e25daf5c90b'
for preset in media:
    if preset['id'] == 'kokoro-82m-vulkan':
        preset['files'] = [f for f in preset['files'] if not f['path'].startswith('kokoro-voice-')]
        for voice in kokoro_voices:
            preset['files'].append(dict(source=voice['source'],
                                        path='voices/kokoro/kokoro-voice-' + voice['id'] + '.gguf',
                                        size=522560, sha256=voice['sha256'],
                                        repository='simonfxr/kokoro.cpp-GGUF',
                                        revision=kokoro_revision))
models = []
for name in ['mistral-7b-instruct-v0.3-q4-0', 'qwen3.8-9b-distill-q4-k-m']:
    recipe_dir = 'recipes' if name == 'mistral-7b-instruct-v0.3-q4-0' else 'catalog'
    recipe = json.loads((root / 'model-tools' / recipe_dir / (name + '.json')).read_text())
    source = recipe['source']
    # Mistral remains installed under its upstream GGUF filename on current consoles;
    # using that ID lets the preset recognize and reuse the existing file.
    preset_id = source['file'] if name == 'mistral-7b-instruct-v0.3-q4-0' else name + '.gguf'
    models.append(dict(id=preset_id, name=recipe['model']['name'], kind=0,
                       repository=source['repository'], revision=source['revision'],
                       files=[dict(source=source['file'], path='', size=source['bytes'], sha256=source['sha256'])]))
models += media
lines = ['// Generated by tools/generate-model-presets.py; SPDX-License-Identifier: GPL-3.0-or-later',
         '#pragma once', '#include <cstddef>', '#include <cstdint>',
         'namespace prospero_model_download {',
         '// repository/revision are null unless a file comes from a different repository than',
         '// the preset, as the speech GGUFs do.',
         'struct PresetFile { const char *source, *path, *sha256; std::uint64_t size;',
         '                    const char *repository, *revision; };',
         'struct Preset { const char *id, *name, *repository, *revision; int kind; std::uint64_t size; const PresetFile *files; std::size_t count; };']
quote = json.dumps
for i, model in enumerate(models):
    assert len(model['revision']) == 40
    if model.get('runtime') == 'prism':
        lines.append('#ifdef PROSPERO_PRISM_RUNTIME')
    lines.append(f'inline constexpr PresetFile preset_files_{i}[] = {{')
    for file in model['files']:
        assert len(file['sha256']) == 64 and all(c in '0123456789abcdef' for c in file['sha256'])
        for path in [file['source'], file['path']]:
            assert not path.startswith('/') and '..' not in path and '\\' not in path
        assert 'revision' not in file or len(file['revision']) == 40
        origin = ', '.join(quote(file[k]) if k in file else 'nullptr' for k in ['repository', 'revision'])
        lines.append('    {' + ', '.join(quote(file[k]) for k in ['source', 'path', 'sha256']) +
                     f", {file['size']}ULL, " + origin + '},')
    lines.append('};')
    if model.get('runtime') == 'prism':
        lines.append('#endif')
lines.append('inline constexpr Preset presets[] = {')
for i, model in enumerate(models):
    if model.get('runtime') == 'prism':
        lines.append('#ifdef PROSPERO_PRISM_RUNTIME')
    lines.append('    {' + ', '.join(quote(model[k]) for k in ['id', 'name', 'repository', 'revision']) +
                 f", {model['kind']}, {sum(f['size'] for f in model['files'])}ULL, preset_files_{i}, {len(model['files'])}" + '},')
    if model.get('runtime') == 'prism':
        lines.append('#endif')
lines += ['};', 'inline constexpr std::size_t preset_count = sizeof(presets) / sizeof(presets[0]);', '}']
(root / 'include/model_presets.hpp').write_text('\n'.join(lines) + '\n')
voice_lines = ['// Generated by tools/generate-model-presets.py; SPDX-License-Identifier: GPL-3.0-or-later',
               '#pragma once', '#include <cstddef>', '#include <cstdint>',
               'namespace prospero_voice {',
               'struct Voice { const char *id, *name, *locale, *filename; };',
               'inline constexpr Voice kokoro[] = {']
for voice in kokoro_voices:
    voice_lines.append('    {' + ', '.join(quote(voice[k]) for k in
                       ['id', 'name', 'locale']) + ', ' +
                       quote('kokoro-voice-' + voice['id'] + '.gguf') + '},')
voice_lines += ['};', 'inline constexpr std::size_t kokoro_count = sizeof(kokoro) / sizeof(kokoro[0]);', '}']
voice_lines.insert(-1, 'inline constexpr Voice chatterbox[] = {')
for voice in voices['chatterbox']:
    voice_lines.insert(-1, '    {' + ', '.join(quote(voice[k]) for k in
                       ['id', 'name', 'locale']) + ', ' + quote(voice['filename']) + '},')
voice_lines.insert(-1, '};')
voice_lines.insert(-1, 'inline constexpr std::size_t chatterbox_count = sizeof(chatterbox) / sizeof(chatterbox[0]);')
(root / 'include/generated_voice_catalog.hpp').write_text('\n'.join(voice_lines) + '\n')
(root / 'assets/web/voice-catalog.js').write_text(
    '// Generated by tools/generate-model-presets.py; SPDX-License-Identifier: GPL-3.0-or-later\n' +
    'window.prosperoVoiceCatalog = ' + json.dumps(voices, ensure_ascii=False, indent=2) + ';\n')
